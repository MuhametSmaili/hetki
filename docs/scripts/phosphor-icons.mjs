// Generates .vitepress/theme/icons.css, which replaces VitePress's built-in
// icons with Phosphor icons. Run from docs/: node scripts/phosphor-icons.mjs
import { writeFileSync } from 'node:fs'
import { h } from 'vue'
import { renderToString } from 'vue/server-renderer'
import * as icons from '@phosphor-icons/vue'

// VitePress icon class -> Phosphor component.
const classes = {
  'arrow-down': 'PhArrowDown',
  'arrow-left': 'PhArrowLeft',
  'arrow-right': 'PhArrowRight',
  'arrow-up': 'PhArrowUp',
  'chevron-down': 'PhCaretDown',
  'chevron-left': 'PhCaretLeft',
  'chevron-right': 'PhCaretRight',
  'chevron-up': 'PhCaretUp',
  'corner-down-left': 'PhArrowElbowDownLeft',
  delete: 'PhBackspace',
  ellipsis: 'PhDotsThree',
  heart: 'PhHeart',
  languages: 'PhTranslate',
  'layout-list': 'PhListDashes',
  moon: 'PhMoon',
  plus: 'PhPlus',
  search: 'PhMagnifyingGlass',
  sparkles: 'PhSparkle',
  'square-pen': 'PhNotePencil',
  sun: 'PhSun',
  'text-align-start': 'PhTextAlignLeft',
}

async function svg(name, fill = 'currentColor') {
  const html = await renderToString(h(icons[name], { size: 24 }))
  return html
    .replace(/<!--.*?-->/g, '')
    .replace(/ (width|height)="[^"]*"/g, '')
    .replace('fill="currentColor"', `fill="${fill}"`)
}

const url = (markup) =>
  `url("data:image/svg+xml,${encodeURIComponent(markup).replace(/'/g, '%27')}")`

const rules = []
for (const [cls, name] of Object.entries(classes)) {
  rules.push(`.vpi-${cls} {\n  --icon: ${url(await svg(name))};\n}`)
}

const grey = 'rgba(128,128,128,1)'
rules.push(
  `:root {\n  --vp-icon-copy: ${url(await svg('PhCopy', grey))};\n` +
    `  --vp-icon-copied: ${url(await svg('PhCheck', grey))};\n}`,
)

writeFileSync(
  new URL('../.vitepress/theme/icons.css', import.meta.url),
  `/* Generated by scripts/phosphor-icons.mjs. Do not edit. */\n\n${rules.join('\n\n')}\n`,
)
